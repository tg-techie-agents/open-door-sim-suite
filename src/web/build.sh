#!/bin/sh
# Builds the app into dist/ (static files, relative URLs).
#   sh src/web/build.sh [outdir]
# Needs bun. No packages are installed and nothing is fetched.
set -eu
web=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$web/../.." && pwd)
out=${1:-"$root/dist"}
mkdir -p "$web/generated" "$out"
cd "$root"

# The example project and the scripts, as a module.
bun -e '
const fs = require("node:fs");
const read = (p) => fs.readFileSync(p, "utf8").replace(/^﻿/, "");
const folder = (d) => Object.fromEntries(fs.readdirSync(d, { withFileTypes: true })
  .filter((e) => e.isFile() && e.name.endsWith(".dxl")).map((e) => e.name).sort()
  .map((n) => [n, read(d + "/" + n)]));
fs.writeFileSync("src/web/generated/embeds.ts",
  "// Generated by src/web/build.sh; do not edit.\n"
  + "export const EXAMPLE: string = " + JSON.stringify(read("examples/example-project.json")) + ";\n"
  + "export const SCRIPTS = " + JSON.stringify({ names: folder("scripts"), layout: folder("scripts/layout") }) + ";\n");
'

# What the start page shows of the tool.
bun -e '
const fs = require("node:fs");
const uri = (n) => "data:image/jpeg;base64," + fs.readFileSync("src/web/shots/" + n + ".jpg").toString("base64");
fs.writeFileSync("src/web/generated/shots.ts", "// Generated by src/web/build.sh; do not edit.\n"
  + "export const SHOTS = " + JSON.stringify({ wide: uri("wide"), narrow: uri("narrow") }) + ";\n");
'

# Names are not minified: error messages use class names.
for name in transport worker; do
  bun build "src/web/$name.ts" --target=browser --format=iife --minify-whitespace --outfile="$out/$name.js"
done
cp src/web/base.js src/web/index.html src/web/web.css src/web/app.js src/web/richtext.js src/web/style.css src/web/trace.js src/web/trace.css src/web/extras.js src/web/select.js src/web/menus.js "$out/"
cp src/web/windows.html src/web/shell.js src/web/shell.css src/web/winchild.js src/web/winchild.css "$out/"
echo "built $out"
